// Writes data/art-manifest.js and data/audio-manifest.js from what is on disk (never from a wish list).
//   LC.ART   = { cards: { <card id>: 'art/cards/<id>.webp' }, ui: { <name>: 'art/ui/<name>.webp' } }
//   LC.AUDIO = { sfx: { <id>: { src, gain } }, music: { <id>: { src, gain, loop } } }
// Audio gains/loop flags come from audio/gains.json (written by tools/gen-audio.mjs). A card with no
// art file is simply absent: the UI must treat a missing entry as an error it reports, not hide.
//   node tools/write-manifest.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const list = (dir, ext) => fs.existsSync(path.join(ROOT, dir)) ? fs.readdirSync(path.join(ROOT, dir)).filter(f => f.endsWith(ext) && fs.statSync(path.join(ROOT, dir, f)).size > 0).sort() : [];
const art = { cards: {}, ui: {} };
for (const f of list('art/cards', '.webp')) art.cards[f.slice(0, -5)] = 'art/cards/' + f;
for (const f of list('art/ui', '.webp')) art.ui[f.slice(0, -5)] = 'art/ui/' + f;
fs.writeFileSync(path.join(ROOT, 'data/art-manifest.js'),
  '// GENERATED by tools/write-manifest.mjs from the files in art/. Do not edit by hand.\n' +
  '// Card art is original (PLAN.md D3): painted by FLUX.2 klein 4B from tools/art/art-prompts.json.\n' +
  '(function () {\n  globalThis.LC = globalThis.LC || {};\n  LC.ART = ' + JSON.stringify(art, null, 2).replace(/\n/g, '\n  ') + ';\n})();\n');
let gains = {};
const gp = path.join(ROOT, 'audio/gains.json');
if (fs.existsSync(gp)) gains = JSON.parse(fs.readFileSync(gp, 'utf8'));
const audio = { sfx: {}, music: {} };
for (const kind of ['sfx', 'music']) for (const f of list('audio/' + kind, '.mp3')) {
  const id = f.slice(0, -4), g = gains[kind + '/' + id] || {};
  audio[kind][id] = { src: 'audio/' + kind + '/' + f, gain: g.gain ?? 1 };
  if (kind === 'music') audio[kind][id].loop = !!g.loop;
}
fs.writeFileSync(path.join(ROOT, 'data/audio-manifest.js'),
  '// GENERATED by tools/write-manifest.mjs from the files in audio/. Do not edit by hand.\n' +
  '// SFX: Stable Audio Open 1.0; music: ACE-Step 1.5 turbo (both local, Audio Studio). gain = playback\n' +
  '// multiplier toward a common loudness (RMS target 0.16 SFX / 0.10 music). Not verified by ear.\n' +
  '(function () {\n  globalThis.LC = globalThis.LC || {};\n  LC.AUDIO = ' + JSON.stringify(audio, null, 2).replace(/\n/g, '\n  ') + ';\n})();\n');
console.log('write-manifest: art ' + Object.keys(art.cards).length + ' cards + ' + Object.keys(art.ui).length + ' ui; audio ' + Object.keys(audio.sfx).length + ' sfx + ' + Object.keys(audio.music).length + ' music');
