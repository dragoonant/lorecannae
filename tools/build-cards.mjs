// Builds data/cards.js and data/decks.js from the Lorcast set dumps in scratch/ and the
// championship lists in data/raw/nacc-decks.txt. Zero dependencies.
//   node tools/build-cards.mjs            (uses cached scratch/s<N>.json)
//   node tools/build-cards.mjs --fetch    (re-downloads the set dumps first)
import fs from 'node:fs';
import path from 'node:path';

import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCRATCH = path.join(ROOT, 'scratch');
const SETS = { TFC: 1, ROTF: 2, ITI: 3, URSU: 4, SSK: 5, AZS: 6, ARI: 7, ROJ: 8, FAB: 9, WSP: 10, WIN: 11, WLD: 12, VINE: 13 };

if (process.argv.includes('--fetch')) {
  fs.mkdirSync(SCRATCH, { recursive: true });
  for (const n of new Set(Object.values(SETS))) {
    const r = await fetch(`https://api.lorcast.com/v0/sets/${n}/cards`);
    if (!r.ok) throw new Error(`set ${n}: HTTP ${r.status}`);
    fs.writeFileSync(path.join(SCRATCH, `s${n}.json`), await r.text());
  }
}

const bySet = {};
for (const n of new Set(Object.values(SETS))) {
  bySet[n] = JSON.parse(fs.readFileSync(path.join(SCRATCH, `s${n}.json`), 'utf8'));
}

const slug = s => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '')
  .replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const lines = fs.readFileSync(path.join(ROOT, 'data/raw/nacc-decks.txt'), 'utf8')
  .split(/\r?\n/).filter(l => l && !l.startsWith('#'));

const cards = {};
const decks = [];
for (const line of lines) {
  const [place, name, archetype, player, inkdecksId, list] = line.split('|');
  const entries = [];
  for (const tok of list.trim().split(/\s+/)) {
    const m = tok.match(/^(\d+)x([A-Z]+)(\d+)$/);
    if (!m) throw new Error(`bad token ${tok} in ${player}`);
    const [, qty, code, num] = m;
    const setNo = SETS[code];
    if (!setNo) throw new Error(`unknown set code ${code}`);
    const src = bySet[setNo].find(c => c.collector_number === num);
    if (!src) throw new Error(`${code}${num} not found in set ${setNo}`);
    const id = slug(src.version ? `${src.name} ${src.version}` : src.name);
    if (!cards[id]) {
      cards[id] = {
        id,
        name: src.name,
        version: src.version || null,
        set: setNo,
        num: Number(num),
        type: src.type,                       // e.g. ["Character"], ["Action","Song"]
        ink: src.ink,
        inks: src.inks || null,
        inkwell: !!src.inkwell,
        cost: src.cost,
        strength: src.strength ?? null,
        willpower: src.willpower ?? null,
        lore: src.lore ?? null,
        moveCost: src.move_cost ?? null,
        classifications: src.classifications || [],
        keywords: src.keywords || [],
        text: src.text || '',
        flavor: src.flavor_text || '',
        rarity: src.rarity,
      };
    }
    entries.push([id, Number(qty)]);
  }
  const total = entries.reduce((a, [, q]) => a + q, 0);
  decks.push({
    id: slug(`${player}-${name}`),
    name, archetype, player, place,
    inks: [...new Set(entries.flatMap(([id]) => cards[id].inks || [cards[id].ink]))].filter(Boolean).sort(),
    source: `inkdecks.com/lorcana-metagame/deck-${inkdecksId}`,
    cards: entries, total,
  });
}

const banner = '// Generated by tools/build-cards.mjs from the Lorcast API (api.lorcast.com) and\n' +
  '// published DLC-NACC 2026 decklists. Card names and rules text are Disney Lorcana game data,\n' +
  '// (c) Disney / Ravensburger; this unofficial fan project is not affiliated with either.\n' +
  '// This is the single file carrying published card names and text (see docs/takedown.md).\n';
fs.writeFileSync(path.join(ROOT, 'data/cards.js'),
  banner + 'globalThis.LC = globalThis.LC || {};\nLC.CARDS = ' + JSON.stringify(cards, null, 1) + ';\n');
fs.writeFileSync(path.join(ROOT, 'data/decks.js'),
  '// Generated by tools/build-cards.mjs. Disney Lorcana Challenge North American Championship,\n' +
  '// Fanfinity, 2026-08-29, Set 13 Core.\nglobalThis.LC = globalThis.LC || {};\nLC.DECKS = ' +
  JSON.stringify(decks, null, 1) + ';\n');

const types = {};
for (const c of Object.values(cards)) { const t = c.type.join('/'); types[t] = (types[t] || 0) + 1; }
console.log(`${Object.keys(cards).length} unique cards, ${decks.length} decks`);
console.log(types);
for (const d of decks) console.log(`  ${d.total}  ${d.inks.join('/')}  ${d.name} (${d.player})`);
